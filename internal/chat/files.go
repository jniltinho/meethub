// FileInfo is the metadata of an uploaded file (Mattermost's FileInfo); the
// bytes are in the storage of internal/files under Path. PostID is nil until
// the file is attached to a message.
type FileInfo struct {
	ID              string  `gorm:"primaryKey;size:26"`
	CreatorID       string  `gorm:"size:26"`
	ChannelID       string  `gorm:"size:26"`
	PostID          *string `gorm:"size:26"`
	Position        int     // its order in the message
	Name            string
	SearchName      string // Name in lowercase, folded here: what the name filter matches
	Extension       string
	Size            int64
	MimeType        string
	Width           int
	Height          int
	HasPreviewImage bool
	Path            string // storage keys, generated by the server
	ThumbnailPath   string
	PreviewPath     string
	CreateAt        int64 `gorm:"autoCreateTime:false"`
	UpdateAt        int64 `gorm:"autoUpdateTime:false"`
	DeleteAt        int64
}

// FileView is the API and event projection of a file (Mattermost's names).
type FileView struct {
	ID              string `json:"id"`
	UserID          string `json:"user_id"`
	ChannelID       string `json:"channel_id"`
	PostID          string `json:"post_id,omitempty"`
	Name            string `json:"name"`
	Extension       string `json:"extension"`
	Size            int64  `json:"size"`
	MimeType        string `json:"mime_type"`
	CreateAt        int64  `json:"create_at"`
	HasPreviewImage bool   `json:"has_preview_image"`
	Width           int    `json:"width,omitempty"`
	Height          int    `json:"height,omitempty"`
}

// PostMetadata carries what a message embeds (Mattermost's post metadata).
type PostMetadata struct {
	Files []FileView `json:"files,omitempty"`
}

func (f *FileInfo) trimIDs() {
	f.ID, f.CreatorID, f.ChannelID = strings.TrimSpace(f.ID), strings.TrimSpace(f.CreatorID), strings.TrimSpace(f.ChannelID)
	if f.PostID != nil {
		id := strings.TrimSpace(*f.PostID)
		f.PostID = &id
	}
}

// View projects the file for users.
func (f *FileInfo) View() FileView {
	v := FileView{
		ID: f.ID, UserID: f.CreatorID, ChannelID: f.ChannelID, Name: f.Name, Extension: f.Extension, Size: f.Size,
		MimeType: f.MimeType, CreateAt: f.CreateAt, HasPreviewImage: f.HasPreviewImage, Width: f.Width, Height: f.Height,
	}
	if f.PostID != nil {
		v.PostID = *f.PostID
	}
	return v
}

// CheckUpload reports whether the caller may add files to the channel: who
// may post there, while it is not archived.
func (s *Service) CheckUpload(ctx context.Context, sub Subject, channelID string) error {
	tx := s.DB.Gorm.WithContext(ctx)
	var ch Channel
	if err := tx.Where("id = ?", channelID).Take(&ch).Error; err != nil {
		if database.IsNotFound(err) {
			return ErrNotFound
		}
		return fmt.Errorf("read channel: %w", err)
	}
	ch.trimIDs()
	a, _, err := accessTx(ctx, tx, sub, &ch)
	if err != nil {
		return err
	}
	if !CanPost(sub, a) {
		return ReadError(sub, a)
	}
	return writable(ctx, tx, &ch)
}

// ReadableFile returns a file the caller may read: one attached to a message
// of a channel they read or, while unattached, their own upload. Anything
// else does not exist for them.
func (s *Service) ReadableFile(ctx context.Context, sub Subject, fileID string) (*FileInfo, error) {
	tx := s.DB.Gorm.WithContext(ctx)
	var f FileInfo
	if err := tx.Where("id = ? AND delete_at = 0", fileID).Take(&f).Error; err != nil {
		if database.IsNotFound(err) {
			return nil, ErrNotFound
		}
		return nil, fmt.Errorf("read file: %w", err)
	}
	f.trimIDs()
	if f.PostID == nil {
		if f.CreatorID != sub.UserID {
			return nil, ErrNotFound
		}
		return &f, nil
	}
	if _, err := s.readableChannel(ctx, tx, sub, f.ChannelID); err != nil {
		if errors.Is(err, ErrForbidden) { // a file never reveals its channel
			return nil, ErrNotFound
		}
		return nil, err
	}
	return &f, nil
}

// attachFiles claims the author's unattached uploads to this channel for the
// post, in the given order; any id that is not one of those fails the post.
func attachFiles(ctx context.Context, tx *gorm.DB, p *Post, ids []string, now int64) error {
	for i, id := range ids {
		res := tx.WithContext(ctx).Model(&FileInfo{}).
			Where("id = ? AND post_id IS NULL AND creator_id = ? AND channel_id = ? AND delete_at = 0", id, p.UserID, p.ChannelID).
			Updates(map[string]any{"post_id": p.ID, "position": i, "update_at": now})
		if res.Error != nil {
			return fmt.Errorf("attach file: %w", res.Error)
		}
		if res.RowsAffected != 1 { // unknown, someone else's, of another channel, already attached or repeated
			return ErrInvalidInput
		}
	}
	return nil
}

// filesForPosts returns the files of several posts, in each message's order.
func filesForPosts(ctx context.Context, tx *gorm.DB, postIDs []string) (map[string][]FileView, error) {
	out := map[string][]FileView{}
	for chunk := range slices.Chunk(postIDs, 500) {
		var rows []FileInfo
		if err := tx.WithContext(ctx).Where("post_id IN ? AND delete_at = 0", chunk).Order("post_id, position").Find(&rows).Error; err != nil {
			return nil, fmt.Errorf("read files: %w", err)
		}
		for i := range rows {
			rows[i].trimIDs()
			out[*rows[i].PostID] = append(out[*rows[i].PostID], rows[i].View())
		}
	}
	return out, nil
}

// deleteFilesOf marks the files of deleted posts as deleted; the cleanup of
// internal/files removes their bytes.
func deleteFilesOf(ctx context.Context, tx *gorm.DB, postIDs []string, now int64) error {
	if err := tx.WithContext(ctx).Model(&FileInfo{}).Where("post_id IN ? AND delete_at = 0", postIDs).
		Updates(map[string]any{"delete_at": now, "update_at": now}).Error; err != nil {
		return fmt.Errorf("delete files: %w", err)
	}
	return nil
}

// ChannelFiles pages the files attached to messages of a channel the caller
// reads, newest first, by an opaque cursor; next is "" on the last page.
func (s *Service) ChannelFiles(ctx context.Context, sub Subject, channelID, cursor string, limit int) ([]FileView, string, error) {
	tx := s.DB.Gorm.WithContext(ctx)
	if _, err := s.readableChannel(ctx, tx, sub, channelID); err != nil {
		return nil, "", err
	}
	return pageFiles(tx.Table("file_infos f").Where("f.channel_id = ?", channelID), cursor, limit)
}

// MyFiles pages the files of every channel and conversation the caller
// belongs to, newest first; q filters by name, ignoring case.
func (s *Service) MyFiles(ctx context.Context, sub Subject, q, cursor string, limit int) ([]FileView, string, error) {
	// the join is the authorization: only files of the caller's channels exist for this query
	sel := s.DB.Gorm.WithContext(ctx).Table("file_infos f").
		Joins("JOIN channel_members m ON m.channel_id = f.channel_id AND m.user_id = ?", sub.UserID)
	if q = strings.TrimSpace(q); q != "" {
		sel = sel.Where("f.search_name LIKE ? ESCAPE '!'", likePattern(strings.ToLower(q)))
	}
	return pageFiles(sel, cursor, limit)
}

func pageFiles(sel *gorm.DB, cursor string, limit int) ([]FileView, string, error) {
	limit = perPage(limit)
	sel = sel.Select("f.*").Where("f.post_id IS NOT NULL AND f.delete_at = 0")
	if cursor != "" {
		at, id, err := parseCursor(cursor)
		if err != nil {
			return nil, "", err
		}
		sel = sel.Where("(f.create_at < ? OR (f.create_at = ? AND f.id < ?))", at, at, id)
	}
	var rows []FileInfo
	if err := sel.Order("f.create_at DESC, f.id DESC").Limit(limit + 1).Scan(&rows).Error; err != nil {
		return nil, "", fmt.Errorf("list files: %w", err)
	}
	next := ""
	if len(rows) > limit {
		rows = rows[:limit]
		next = fmt.Sprintf("%d:%s", rows[limit-1].CreateAt, strings.TrimSpace(rows[limit-1].ID))
	}
	out := make([]FileView, len(rows))
	for i := range rows {
		rows[i].trimIDs()
		out[i] = rows[i].View()
	}
	return out, next, nil
}
